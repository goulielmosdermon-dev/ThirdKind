export function vimeoWatchUrl(vimeoId: string): `https://vimeo.com/${string}` {
  const hash = VIMEO_PRIVACY_HASH[vimeoId];
  return hash
    ? `https://vimeo.com/${vimeoId}/${hash}`
    : `https://vimeo.com/${vimeoId}`;
}

export function vimeoIdFromUrl(url: string): string | undefined {
  const parts = url.split('/').filter(Boolean);
  const last = parts.at(-1) ?? '';
  const prev = parts.at(-2) ?? '';
  if (/^\d+$/.test(last)) {
    return last;
  }
  if (/^\d+$/.test(prev) && /^[a-f0-9]+$/i.test(last)) {
    return prev;
  }
  return undefined;
}

export function vimeoPlayerSrc(
  vimeoId: string,
  extra: Record<string, string> = {},
): string {
  const params = new URLSearchParams();
  const hash = VIMEO_PRIVACY_HASH[vimeoId];
  if (hash) {
    params.set('h', hash);
  }
  for (const [key, value] of Object.entries(extra)) {
    params.set(key, value);
  }
  const query = params.toString();
  return query
    ? `https://player.vimeo.com/video/${vimeoId}?${query}`
    : `https://player.vimeo.com/video/${vimeoId}`;
}
